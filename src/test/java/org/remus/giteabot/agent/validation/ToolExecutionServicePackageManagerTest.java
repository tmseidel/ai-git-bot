package org.remus.giteabot.agent.validation;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.remus.giteabot.agent.packagemanager.PackageManagerDetector;
import org.remus.giteabot.agent.packagemanager.YarnCommandBuilder;
import org.remus.giteabot.agent.tools.ToolCatalog;
import org.remus.giteabot.config.AgentConfigProperties;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * The tool-layer half of Yarn support: npm is refused in a Yarn checkout even when the bot
 * offers it, and the yarn tool is gated by the operator's tool configuration like every
 * other validation tool.
 */
class ToolExecutionServicePackageManagerTest {

    private AgentConfigProperties config;
    private ToolExecutionService service;

    @TempDir
    Path workspace;

    @BeforeEach
    void setUp() {
        config = new AgentConfigProperties();
        service = newService(config);
    }

    @Test
    void npmIsRefusedInARepositoryWithAYarnLockfile() throws IOException {
        Files.writeString(workspace.resolve("yarn.lock"), "# yarn lockfile v1\n");

        ToolResult result = service.executeTool(Workspace.unmanaged(workspace), "npm", List.of("install"));

        assertThat(result.success()).isFalse();
        assertThat(result.error()).contains("managed by Yarn", "yarn.lock", "`yarn` tool");
    }

    @Test
    void npmIsRefusedWhenPackageJsonDeclaresYarn() throws IOException {
        Files.writeString(workspace.resolve("package.json"), """
                {"name": "app", "packageManager": "yarn@4.1.1"}
                """);

        ToolResult result = service.executeTool(Workspace.unmanaged(workspace), "npm", List.of("add", "x"));

        assertThat(result.success()).isFalse();
        assertThat(result.error()).contains("packageManager", "yarn@4.1.1");
    }

    @Test
    void npmIsNotRefusedForAnNpmRepository() throws IOException {
        Files.writeString(workspace.resolve("package.json"), "{\"name\": \"app\"}\n");
        Files.writeString(workspace.resolve("package-lock.json"), "{}\n");

        ToolResult result = service.executeTool(Workspace.unmanaged(workspace), "npm", List.of("--version"));

        // The command itself may or may not exist in the test image; either way the refusal
        // must not fire, because this repository is not Yarn-managed.
        assertThat(result.error()).doesNotContain("managed by Yarn");
    }

    @Test
    void yarnIsRefusedForAModernLockfileWithoutAPin() throws IOException {
        Files.writeString(workspace.resolve("yarn.lock"), """
                # This file is generated by running "yarn install" inside your project.

                __metadata:
                  version: 8
                """);

        ToolResult result = service.executeTool(Workspace.unmanaged(workspace), "yarn", List.of("install"));

        assertThat(result.success()).isFalse();
        assertThat(result.error()).contains("no Yarn version is pinned", "packageManager", "v1 format");
    }

    @Test
    void yarnWithoutArgumentsExplainsWhatItTakes() {
        ToolResult result = service.executeTool(Workspace.unmanaged(workspace), "yarn", List.of());

        assertThat(result.success()).isFalse();
        assertThat(result.error()).contains("install", "add", "remove");
    }

    @Test
    void yarnIsAdvertisedAsAValidationToolWithItsOwnGuidance() {
        ToolCatalog catalog = new ToolCatalog(config);

        assertThat(catalog.validationToolNames()).contains("yarn");
        assertThat(catalog.nativeDescriptors(ToolCatalog.Role.CODING, null, null))
                .extracting(org.remus.giteabot.ai.ToolDescriptor::name)
                .contains("yarn");
        assertThat(catalog.describeFor(ToolCatalog.Role.CODING, "yarn"))
                .hasValueSatisfying(description -> assertThat(description).contains("Yarn"));
        assertThat(catalog.usageHint("yarn")).isPresent();
        assertThat(catalog.usageHint("npm")).isPresent();
    }

    @Test
    void anOperatorsToolConfigurationStillGatesYarn() {
        config.getValidation().setAvailableTools(List.of("mvn"));
        ToolExecutionService restricted = newService(config);

        ToolResult result = restricted.executeTool(Workspace.unmanaged(workspace), "yarn", List.of("install"));

        assertThat(result.success()).isFalse();
        assertThat(result.output()).contains("not available");
        assertThat(result.error()).doesNotContain("managed by Yarn");
    }

    private static ToolExecutionService newService(AgentConfigProperties config) {
        return new ToolExecutionService(config, new ToolCatalog(config),
                new PackageManagerDetector(), new YarnCommandBuilder(config));
    }
}
