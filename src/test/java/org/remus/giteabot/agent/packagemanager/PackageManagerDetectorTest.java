package org.remus.giteabot.agent.packagemanager;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;

import static org.assertj.core.api.Assertions.assertThat;

class PackageManagerDetectorTest {

    private final PackageManagerDetector detector = new PackageManagerDetector();

    @TempDir
    Path workspace;

    @Test
    void packageManagerFieldNamesYarnWithItsPin() throws IOException {
        write("package.json", """
                {"name": "app", "packageManager": "yarn@4.1.1+sha512.abc"}
                """);

        PackageManagerDetection detection = detector.detect(workspace);

        assertThat(detection.manager()).isEqualTo(PackageManager.YARN);
        assertThat(detection.yarnVersionSpec()).isEqualTo("4.1.1");
        assertThat(detection.yarnVersionFromManifest()).isTrue();
        assertThat(detection.yarnPath()).isNull();
        assertThat(detection.evidence()).contains("packageManager");
    }

    @Test
    void packageManagerFieldWinsOverALockfile() throws IOException {
        write("package.json", """
                {"name": "app", "packageManager": "npm@10.5.0"}
                """);
        write("yarn.lock", "# yarn lockfile v1\n");

        PackageManagerDetection detection = detector.detect(workspace);

        assertThat(detection.manager()).isEqualTo(PackageManager.NPM);
        assertThat(detection.isYarn()).isFalse();
    }

    @Test
    void yarnLockAloneMeansYarnClassic() throws IOException {
        write("yarn.lock", """
                # THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
                # yarn lockfile v1


                left-pad@^1.3.0:
                  version "1.3.0"
                """);

        PackageManagerDetection detection = detector.detect(workspace);

        assertThat(detection.manager()).isEqualTo(PackageManager.YARN);
        assertThat(detection.yarnVersionSpec()).isEqualTo("1");
        assertThat(detection.yarnVersionFromManifest()).isFalse();
        assertThat(detection.evidence()).isEqualTo("yarn.lock");
    }

    @Test
    void aModernLockfileNamesYarnWithoutAVersion() throws IOException {
        write("yarn.lock", """
                # This file is generated by running "yarn install" inside your project.

                __metadata:
                  version: 8
                """);

        PackageManagerDetection detection = detector.detect(workspace);

        assertThat(detection.manager()).isEqualTo(PackageManager.YARN);
        assertThat(detection.yarnVersionSpec()).isNull();
        assertThat(detection.yarnPath()).isNull();
        assertThat(detection.yarnVersionFromManifest()).isFalse();
    }

    @Test
    void aVendoredReleaseIsPickedUpFromYarnrc() throws IOException {
        write("yarn.lock", """
                # This file is generated by running "yarn install" inside your project.

                __metadata:
                  version: 8
                """);
        write(".yarnrc.yml", "nodeLinker: node-modules\nyarnPath: .yarn/releases/yarn-4.2.0.cjs\n");
        write(".yarn/releases/yarn-4.2.0.cjs", "// release\n");

        PackageManagerDetection detection = detector.detect(workspace);

        assertThat(detection.manager()).isEqualTo(PackageManager.YARN);
        assertThat(detection.yarnPath()).isEqualTo(".yarn/releases/yarn-4.2.0.cjs");
        assertThat(detection.yarnVersionSpec()).isNull();
        assertThat(detection.yarnVersionFromManifest()).isFalse();
    }

    @Test
    void aVendoredReleaseWithoutALockfileStillNamesYarn() throws IOException {
        write(".yarnrc.yml", "yarnPath: \".yarn/releases/yarn-3.6.4.cjs\"\n");
        write(".yarn/releases/yarn-3.6.4.cjs", "// release\n");

        PackageManagerDetection detection = detector.detect(workspace);

        assertThat(detection.manager()).isEqualTo(PackageManager.YARN);
        assertThat(detection.yarnPath()).isEqualTo(".yarn/releases/yarn-3.6.4.cjs");
        assertThat(detection.evidence()).isEqualTo(".yarnrc.yml");
    }

    @Test
    void aYarnPathOutsideTheWorkspaceIsIgnored() throws IOException {
        write("yarn.lock", """
                # This file is generated by running "yarn install" inside your project.
                """);
        write(".yarnrc.yml", "yarnPath: ../../evil.cjs\n");
        Files.writeString(workspace.getParent().resolve("evil.cjs"), "// outside\n");

        PackageManagerDetection detection = detector.detect(workspace);

        assertThat(detection.manager()).isEqualTo(PackageManager.YARN);
        assertThat(detection.yarnPath()).isNull();
    }

    @Test
    void aMissingVendoredReleaseIsIgnored() throws IOException {
        write(".yarnrc.yml", "yarnPath: .yarn/releases/yarn-4.2.0.cjs\n");

        assertThat(detector.detect(workspace).yarnPath()).isNull();
    }

    @Test
    void packageLockMeansNpm() throws IOException {
        write("package-lock.json", "{}\n");

        assertThat(detector.detect(workspace).manager()).isEqualTo(PackageManager.NPM);
    }

    @Test
    void aRepositoryWithBothLockfilesIsTreatedAsYarn() throws IOException {
        write("yarn.lock", "# yarn lockfile v1\n");
        write("package-lock.json", "{}\n");

        assertThat(detector.detect(workspace).manager()).isEqualTo(PackageManager.YARN);
    }

    @Test
    void noMarkerStaysUnknownSoNpmKeepsWorking() {
        PackageManagerDetection detection = detector.detect(workspace);

        assertThat(detection.manager()).isEqualTo(PackageManager.UNKNOWN);
        assertThat(detection.isYarn()).isFalse();
    }

    private void write(String path, String content) throws IOException {
        Path file = workspace.resolve(path);
        Files.createDirectories(file.getParent());
        Files.writeString(file, content);
    }
}
