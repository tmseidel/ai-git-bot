-- Review-tool operation receipts (implementation plan step 1b).
--
-- One row per (review, operationId). The row is written in the transaction that applied the
-- mutation, so a retried call replays its result instead of applying it twice, and a failed
-- mutation leaves neither a finding nor a receipt. The unique constraint is what makes two
-- concurrent deliveries of the same operation end with exactly one applied mutation.
--
-- Idempotent: every statement can be re-applied.

CREATE TABLE IF NOT EXISTS review_tool_operations (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id     BIGINT       NOT NULL,
    operation_id  VARCHAR(128) NOT NULL,
    tool          VARCHAR(64)  NOT NULL,
    argument_hash VARCHAR(64)  NOT NULL,
    result_json   TEXT         NOT NULL,
    created_at    TIMESTAMP    NOT NULL,
    CONSTRAINT uk_review_tool_operations_review_operation UNIQUE (review_id, operation_id),
    CONSTRAINT fk_review_tool_operations_review
        FOREIGN KEY (review_id) REFERENCES review_records(id) ON DELETE CASCADE
);
