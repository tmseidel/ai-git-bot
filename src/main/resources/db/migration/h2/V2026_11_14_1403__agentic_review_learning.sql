-- Agentic review: structured reviews, publication receipts, learning evidence and feedback.
--
-- One migration for the whole feature because it ships as one release: nothing here has been
-- deployed, so there is no upgrade path to preserve between the pieces, and a fresh install would
-- otherwise replay seven files that only ever exist together. The version keeps the date of the
-- first table so ordering against unrelated migrations (persistent logins, provider enum) does not
-- change.
--
-- The normalized review record is the source of truth; the published comment is a rendering of it,
-- the formal decision is computed from its findings, and feedback points at its rows. References
-- (O<n>, O<n>-F<m>, O<n>-A, FB<n>) are reserved from reference_sequences before the row is written,
-- so no reference ever depends on a provider comment id or on model output.
--
-- Idempotent: every statement can be re-applied, and the guarded UPDATE/DELETE below match nothing
-- once they have run.

-- ---------------------------------------------------------------------------------------------
-- Reference counters
-- ---------------------------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS reference_sequences (
    name       VARCHAR(32) NOT NULL PRIMARY KEY,
    next_value BIGINT      NOT NULL
);

INSERT INTO reference_sequences (name, next_value)
SELECT 'workflow_output', 1
WHERE NOT EXISTS (SELECT 1 FROM reference_sequences WHERE name = 'workflow_output');

INSERT INTO reference_sequences (name, next_value)
SELECT 'workflow_feedback', 1
WHERE NOT EXISTS (SELECT 1 FROM reference_sequences WHERE name = 'workflow_feedback');

-- ---------------------------------------------------------------------------------------------
-- Structured review records
--
-- One output per generated result (the review, later other stage outputs), one review record per
-- output, findings and locations normalized so feedback and evaluation can address a single
-- finding, and one assessment bound to the draft revision it judged. Server metadata (coverage,
-- hashes, revisions, timestamps) lives here because the model cannot be trusted to supply it.
-- ---------------------------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS workflow_outputs (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference              VARCHAR(32)  NOT NULL,
    git_integration_id     BIGINT       NOT NULL,
    bot_id                 BIGINT       NOT NULL,
    repo_owner             VARCHAR(255) NOT NULL,
    repo_name              VARCHAR(255) NOT NULL,
    provider_repository_id VARCHAR(255),
    pr_number              BIGINT       NOT NULL,
    workflow_key           VARCHAR(64)  NOT NULL,
    stage                  VARCHAR(32)  NOT NULL,
    pr_workflow_run_id     BIGINT,
    invocation_id          VARCHAR(36)  NOT NULL,
    created_at             TIMESTAMP    NOT NULL,
    CONSTRAINT uk_workflow_outputs_reference UNIQUE (reference),
    CONSTRAINT uk_workflow_outputs_invocation_stage UNIQUE (invocation_id, workflow_key, stage)
);

CREATE INDEX IF NOT EXISTS idx_workflow_outputs_pr
    ON workflow_outputs (git_integration_id, bot_id, repo_owner, repo_name, pr_number);

CREATE TABLE IF NOT EXISTS review_records (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    output_id             BIGINT      NOT NULL,
    state                 VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    schema_version        INTEGER     NOT NULL DEFAULT 1,
    base_sha              VARCHAR(64),
    head_sha              VARCHAR(64),
    draft_revision        INTEGER     NOT NULL DEFAULT 0,
    server_coverage_note  TEXT,
    content_hash          VARCHAR(64),
    finalized_at          TIMESTAMP,
    created_at            TIMESTAMP   NOT NULL,
    updated_at            TIMESTAMP   NOT NULL,
    CONSTRAINT uk_review_records_output UNIQUE (output_id),
    CONSTRAINT fk_review_records_output
        FOREIGN KEY (output_id) REFERENCES workflow_outputs(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_review_records_state ON review_records (state);

CREATE TABLE IF NOT EXISTS review_findings (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id            BIGINT       NOT NULL,
    ordinal              INTEGER      NOT NULL,
    client_key           VARCHAR(128) NOT NULL,
    revision             INTEGER      NOT NULL,
    severity             VARCHAR(16)  NOT NULL,
    category             VARCHAR(64)  NOT NULL,
    title                VARCHAR(512) NOT NULL,
    explanation          TEXT         NOT NULL,
    impact               TEXT         NOT NULL,
    recommendation       TEXT         NOT NULL,
    withdrawn            BOOLEAN      NOT NULL DEFAULT FALSE,
    withdrawal_reason    VARCHAR(1024),
    created_at           TIMESTAMP    NOT NULL,
    updated_at           TIMESTAMP    NOT NULL,
    CONSTRAINT uk_review_findings_review_ordinal UNIQUE (review_id, ordinal),
    CONSTRAINT uk_review_findings_review_client_key UNIQUE (review_id, client_key),
    CONSTRAINT fk_review_findings_review
        FOREIGN KEY (review_id) REFERENCES review_records(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS review_finding_locations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    finding_id  BIGINT        NOT NULL,
    position    INTEGER       NOT NULL,
    path        VARCHAR(1024) NOT NULL,
    side        VARCHAR(8)    NOT NULL,
    start_line  INTEGER,
    end_line    INTEGER,
    description TEXT          NOT NULL,
    CONSTRAINT uk_review_finding_locations_position UNIQUE (finding_id, position),
    CONSTRAINT fk_review_finding_locations_finding
        FOREIGN KEY (finding_id) REFERENCES review_findings(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS review_assessments (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id         BIGINT      NOT NULL,
    summary           TEXT        NOT NULL,
    conclusion        VARCHAR(32) NOT NULL,
    reviewed_areas    TEXT,
    limitations       TEXT,
    assessed_revision INTEGER     NOT NULL,
    created_at        TIMESTAMP   NOT NULL,
    updated_at        TIMESTAMP   NOT NULL,
    CONSTRAINT uk_review_assessments_review UNIQUE (review_id),
    CONSTRAINT fk_review_assessments_review
        FOREIGN KEY (review_id) REFERENCES review_records(id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------------------------------
-- Review-tool operation receipts
--
-- One row per (review, operationId), written in the transaction that applied the mutation: a
-- retried call replays its result instead of applying it twice, a failed mutation leaves neither a
-- finding nor a receipt, and the unique constraint is what makes two concurrent deliveries of the
-- same operation end with exactly one applied mutation.
-- ---------------------------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS review_tool_operations (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id     BIGINT       NOT NULL,
    operation_id  VARCHAR(128) NOT NULL,
    tool          VARCHAR(64)  NOT NULL,
    argument_hash VARCHAR(64)  NOT NULL,
    result_json   TEXT         NOT NULL,
    created_at    TIMESTAMP    NOT NULL,
    CONSTRAINT uk_review_tool_operations_review_operation UNIQUE (review_id, operation_id),
    CONSTRAINT fk_review_tool_operations_review
        FOREIGN KEY (review_id) REFERENCES review_records(id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------------------------------
-- Publication bookkeeping
--
-- One row per delivery attempt. The intent is written before the Git call, so a crash leaves a
-- visible PENDING row instead of a silently missing review; UNCERTAIN records an outcome that
-- cannot be claimed either way. Rendered Markdown is a delivery snapshot, never the review's
-- source.
-- ---------------------------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS review_publications (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id         BIGINT       NOT NULL,
    output_id         BIGINT       NOT NULL,
    provider          VARCHAR(32)  NOT NULL,
    channel           VARCHAR(64)  NOT NULL,
    renderer_version  INTEGER      NOT NULL DEFAULT 1,
    render_revision   INTEGER      NOT NULL DEFAULT 1,
    render_hash       VARCHAR(64)  NOT NULL,
    state             VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
    provider_receipt  VARCHAR(255),
    rendered_markdown TEXT,
    created_at        TIMESTAMP    NOT NULL,
    updated_at        TIMESTAMP    NOT NULL,
    CONSTRAINT uk_review_publications_review_revision UNIQUE (review_id, render_revision),
    CONSTRAINT fk_review_publications_review
        FOREIGN KEY (review_id) REFERENCES review_records(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_review_publications_state ON review_publications (state);

-- ---------------------------------------------------------------------------------------------
-- Supplemental learning evidence
--
-- The task, diff, prompt and revisions a review was produced from. Written only when the
-- agentic-review configuration enables feedback collection, bounded in size, and marked incomplete
-- rather than silently shortened. No credentials are ever stored.
-- ---------------------------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS workflow_output_snapshots (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id                 BIGINT       NOT NULL,
    output_id                 BIGINT       NOT NULL,
    pr_title                  TEXT,
    pr_body                   TEXT,
    diff_text                 TEXT,
    system_prompt             TEXT,
    system_prompt_hash        VARCHAR(64),
    base_sha                  VARCHAR(64),
    head_sha                  VARCHAR(64),
    base_ref                  VARCHAR(512),
    head_ref                  VARCHAR(512),
    provider_repository_id    VARCHAR(255),
    provider                  VARCHAR(64),
    model                     VARCHAR(128),
    workflow_configuration_id BIGINT,
    settings_hash             VARCHAR(64),
    complete                  BOOLEAN      NOT NULL DEFAULT FALSE,
    incomplete_reason         VARCHAR(1024),
    created_at                TIMESTAMP    NOT NULL,
    CONSTRAINT uk_workflow_output_snapshots_review UNIQUE (review_id),
    CONSTRAINT fk_workflow_output_snapshots_review
        FOREIGN KEY (review_id) REFERENCES review_records(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_workflow_output_snapshots_created
    ON workflow_output_snapshots (created_at);

-- ---------------------------------------------------------------------------------------------
-- Feedback on agentic-review targets
--
-- One row per reviewer assessment of one target (review, finding or assessment). The target is a
-- typed foreign key, so a rerendered or corrected comment cannot retarget existing feedback; the
-- reason is the only free text and is bounded by the column.
--
-- source_key is the normalized identity of the submitting comment (integration, bot, repository,
-- subject kind/number, comment kind, comment id). Its unique constraint makes webhook redelivery
-- harmless: one comment produces one record.
--
-- Historical rows keep their own integration/bot/repository identity, so replacing, cloning or
-- deleting a workflow configuration never cascades into learning history.
-- ---------------------------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS workflow_feedback (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference              VARCHAR(32)  NOT NULL,
    output_id              BIGINT       NOT NULL,
    review_id              BIGINT       NOT NULL,
    target_reference       VARCHAR(32)  NOT NULL,
    target_type            VARCHAR(16)  NOT NULL,
    finding_id             BIGINT,
    verdict                VARCHAR(24)  NOT NULL,
    reason                 VARCHAR(4000),
    actor                  VARCHAR(255) NOT NULL,
    state                  VARCHAR(16)  NOT NULL DEFAULT 'EFFECTIVE',
    superseded_by          VARCHAR(32),
    git_integration_id     BIGINT       NOT NULL,
    bot_id                 BIGINT       NOT NULL,
    repo_owner             VARCHAR(255) NOT NULL,
    repo_name              VARCHAR(255) NOT NULL,
    provider_repository_id VARCHAR(255),
    pr_number              BIGINT       NOT NULL,
    subject_kind           VARCHAR(16)  NOT NULL,
    subject_number         BIGINT       NOT NULL,
    comment_kind           VARCHAR(32)  NOT NULL,
    comment_id             VARCHAR(128) NOT NULL,
    source_key             VARCHAR(64)  NOT NULL,
    created_at             TIMESTAMP    NOT NULL,
    updated_at             TIMESTAMP    NOT NULL,
    CONSTRAINT uk_workflow_feedback_reference UNIQUE (reference),
    CONSTRAINT uk_workflow_feedback_source UNIQUE (source_key),
    CONSTRAINT fk_workflow_feedback_output
        FOREIGN KEY (output_id) REFERENCES workflow_outputs(id) ON DELETE CASCADE,
    CONSTRAINT fk_workflow_feedback_review
        FOREIGN KEY (review_id) REFERENCES review_records(id) ON DELETE CASCADE,
    CONSTRAINT fk_workflow_feedback_finding
        FOREIGN KEY (finding_id) REFERENCES review_findings(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_workflow_feedback_output ON workflow_feedback (output_id);

CREATE INDEX IF NOT EXISTS idx_workflow_feedback_scope
    ON workflow_feedback (git_integration_id, bot_id, repo_owner, repo_name, pr_number);

CREATE INDEX IF NOT EXISTS idx_workflow_feedback_target_actor
    ON workflow_feedback (output_id, target_type, finding_id, actor);

-- ---------------------------------------------------------------------------------------------
-- Seeded agentic-review role description
--
-- An agentic review is published from the structured draft the model records through the review
-- tools, not from Markdown the model writes. The seeded role description still ended with "reply
-- with your final review as plain Markdown and stop calling tools", which contradicts that
-- protocol (a text reply is never published).
--
-- Only rows that still carry that seeded sentence are touched: an operator-customised role
-- description is their decision, so this replaces the sentence and leaves everything else —
-- including customised criteria around it — as it is.
-- ---------------------------------------------------------------------------------------------

UPDATE system_prompts
SET review_agent_system_prompt = REPLACE(
        REPLACE(
            review_agent_system_prompt,
            'reply with your final review as',
            'record the review with the review tools:'),
        'plain Markdown and stop calling tools.',
        'submit each finding, set the overall assessment, then complete the review. '
        || 'The application renders the published comment from those records, so do not write '
        || 'the review yourself.')
WHERE review_agent_system_prompt LIKE '%plain Markdown and stop calling tools.%';

-- ---------------------------------------------------------------------------------------------
-- The approval prompt has no consumer
--
-- The review decision is computed from the persisted findings and the configured severity
-- thresholds, so nothing reads formalReviewDecisionPrompt. The parameter is gone from the workflow
-- schema; this removes the row a selection saved before that removal. In a fresh install the
-- parameter never existed and the DELETE matches nothing.
-- ---------------------------------------------------------------------------------------------

DELETE FROM workflow_selection_params
WHERE name = 'formalReviewDecisionPrompt'
  AND workflow_selection_id IN (
      SELECT id FROM workflow_selections WHERE workflow_key = 'agentic-review'
  );
