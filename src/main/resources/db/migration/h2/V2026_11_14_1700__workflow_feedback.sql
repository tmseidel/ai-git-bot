-- Feedback on agentic-review targets (implementation plan step 2).
--
-- One row per reviewer assessment of one target (review, finding, or assessment). The target is a
-- typed foreign key, so a rerendered or corrected comment cannot retarget existing feedback; the
-- reason is the only free text and is bounded by the column.
--
-- source_key is the normalized identity of the submitting comment (integration, bot, repository,
-- subject kind/number, comment kind, comment id). Its unique constraint is what makes webhook
-- redelivery harmless: one comment produces one record.
--
-- historical rows keep their own integration/bot/repository identity, so replacing, cloning or
-- deleting a workflow configuration never cascades into learning history.
--
-- Idempotent: every statement can be re-applied.

INSERT INTO reference_sequences (name, next_value)
SELECT 'workflow_feedback', 1
WHERE NOT EXISTS (SELECT 1 FROM reference_sequences WHERE name = 'workflow_feedback');

CREATE TABLE IF NOT EXISTS workflow_feedback (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference              VARCHAR(32)  NOT NULL,
    output_id              BIGINT       NOT NULL,
    review_id              BIGINT       NOT NULL,
    target_reference       VARCHAR(32)  NOT NULL,
    target_type            VARCHAR(16)  NOT NULL,
    finding_id             BIGINT,
    verdict                VARCHAR(24)  NOT NULL,
    reason                 VARCHAR(4000),
    actor                  VARCHAR(255) NOT NULL,
    state                  VARCHAR(16)  NOT NULL DEFAULT 'EFFECTIVE',
    superseded_by          VARCHAR(32),
    git_integration_id     BIGINT       NOT NULL,
    bot_id                 BIGINT       NOT NULL,
    repo_owner             VARCHAR(255) NOT NULL,
    repo_name              VARCHAR(255) NOT NULL,
    provider_repository_id VARCHAR(255),
    pr_number              BIGINT       NOT NULL,
    subject_kind           VARCHAR(16)  NOT NULL,
    subject_number         BIGINT       NOT NULL,
    comment_kind           VARCHAR(32)  NOT NULL,
    comment_id             VARCHAR(128) NOT NULL,
    source_key             VARCHAR(64)  NOT NULL,
    created_at             TIMESTAMP    NOT NULL,
    updated_at             TIMESTAMP    NOT NULL,
    CONSTRAINT uk_workflow_feedback_reference UNIQUE (reference),
    CONSTRAINT uk_workflow_feedback_source UNIQUE (source_key),
    CONSTRAINT fk_workflow_feedback_output
        FOREIGN KEY (output_id) REFERENCES workflow_outputs(id) ON DELETE CASCADE,
    CONSTRAINT fk_workflow_feedback_review
        FOREIGN KEY (review_id) REFERENCES review_records(id) ON DELETE CASCADE,
    CONSTRAINT fk_workflow_feedback_finding
        FOREIGN KEY (finding_id) REFERENCES review_findings(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_workflow_feedback_output ON workflow_feedback (output_id);

CREATE INDEX IF NOT EXISTS idx_workflow_feedback_scope
    ON workflow_feedback (git_integration_id, bot_id, repo_owner, repo_name, pr_number);

CREATE INDEX IF NOT EXISTS idx_workflow_feedback_target_actor
    ON workflow_feedback (output_id, target_type, finding_id, actor);
