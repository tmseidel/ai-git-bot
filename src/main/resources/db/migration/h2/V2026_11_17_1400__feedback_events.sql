-- ---------------------------------------------------------------------------------------------
-- Feedback history and confirmation tracking
--
-- workflow_feedback.source_key was stored as the readable concatenation of the comment identity,
-- which overflows its 64 characters for long repository names. It is now the SHA-256 hex of that
-- text; existing readable keys (they contain '|') are rehashed so redeliveries still match.
--
-- workflow_feedback_events is the append-only history of every record (submitted, superseded,
-- retracted). Events the bot confirms in a comment carry the confirmation's delivery state, so a
-- redelivered webhook neither confirms twice nor re-posts a confirmation of uncertain delivery.
-- Backfilled confirmations are UNCERTAIN: whether they reached the pull request is unknown.
-- ---------------------------------------------------------------------------------------------

UPDATE workflow_feedback
SET source_key = LOWER(RAWTOHEX(HASH('SHA-256', STRINGTOUTF8(source_key))))
WHERE source_key LIKE '%|%';

CREATE TABLE IF NOT EXISTS workflow_feedback_events (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feedback_id       BIGINT       NOT NULL,
    event_type        VARCHAR(16)  NOT NULL,
    actor             VARCHAR(255) NOT NULL,
    related_reference VARCHAR(32),
    acknowledgement   VARCHAR(16),
    created_at        TIMESTAMP    NOT NULL,
    acknowledged_at   TIMESTAMP,
    CONSTRAINT fk_workflow_feedback_events_feedback
        FOREIGN KEY (feedback_id) REFERENCES workflow_feedback(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_workflow_feedback_events_feedback
    ON workflow_feedback_events (feedback_id, event_type);

INSERT INTO workflow_feedback_events (feedback_id, event_type, actor, acknowledgement, created_at)
SELECT id, 'SUBMITTED', actor, 'UNCERTAIN', created_at FROM workflow_feedback
WHERE NOT EXISTS (SELECT 1 FROM workflow_feedback_events e
                  WHERE e.feedback_id = workflow_feedback.id AND e.event_type = 'SUBMITTED');

INSERT INTO workflow_feedback_events (feedback_id, event_type, actor, related_reference, created_at)
SELECT id, 'SUPERSEDED', actor, superseded_by, updated_at FROM workflow_feedback
WHERE state = 'SUPERSEDED'
  AND NOT EXISTS (SELECT 1 FROM workflow_feedback_events e
                  WHERE e.feedback_id = workflow_feedback.id AND e.event_type = 'SUPERSEDED');

INSERT INTO workflow_feedback_events (feedback_id, event_type, actor, acknowledgement, created_at)
SELECT id, 'RETRACTED', actor, 'UNCERTAIN', updated_at FROM workflow_feedback
WHERE state = 'RETRACTED'
  AND NOT EXISTS (SELECT 1 FROM workflow_feedback_events e
                  WHERE e.feedback_id = workflow_feedback.id AND e.event_type = 'RETRACTED');
